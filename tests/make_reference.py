"""Generates the moons data used by the lab and reference results from scikit-learn.

    python tests/make_reference.py

Writes:
  moons.js                 make_moons(200, noise=0.05, random_state=0), loaded by the page
  tests/reference.json     values that tests/verify.js compares the JavaScript engine against
"""
import json
from pathlib import Path

import numpy as np
from sklearn.cluster import DBSCAN, KMeans
from sklearn.datasets import make_blobs, make_moons
from sklearn.metrics import adjusted_rand_score, silhouette_score
from sklearn.preprocessing import StandardScaler

ROOT = Path(__file__).resolve().parent.parent

HOURS = list(range(1, 11))
SCORES = [58, 30, 59, 32, 61, 86, 42, 90, 92, 45]
LETTERS = "ABCDEFGHIJ"
GOOD_START = [1, 4, 8]   # B, E, I = 30, 61, 92
POOR_START = [6, 5, 7]   # G, F, H = 42, 86, 90


def lloyd(X, start_indices):
    """One run from fixed starting points, so the result can be compared step for step."""
    km = KMeans(n_clusters=len(start_indices), init=X[start_indices], n_init=1,
                algorithm="lloyd", tol=0).fit(X)
    return {"centers": km.cluster_centers_.round(6).tolist(),
            "labels": km.labels_.tolist(),
            "inertia": round(float(km.inertia_), 6)}


def best_by_k(X, ks):
    out = {}
    for k in ks:
        km = KMeans(n_clusters=k, n_init=50, random_state=0).fit(X)
        row = {"inertia": round(float(km.inertia_), 6)}
        if k >= 2:
            row["silhouette"] = round(float(silhouette_score(X, km.labels_)), 6)
        out[str(k)] = row
    return out


score_only = np.array(SCORES, dtype=float).reshape(-1, 1)
two_d = np.column_stack([HOURS, SCORES]).astype(float)
scaler = StandardScaler().fit(two_d)
scaled = scaler.transform(two_d)

X_moons, y_moons = make_moons(n_samples=200, noise=0.05, random_state=0)
X_moons = X_moons.round(4)
km_moons = KMeans(n_clusters=2, n_init=10, random_state=0).fit(X_moons)

(ROOT / "moons.js").write_text(
    "// make_moons(n_samples=200, noise=0.05, random_state=0), rounded to 4 decimals.\n"
    "// Generated by tests/make_reference.py.\n"
    "window.KM_MOONS = " + json.dumps({"X": X_moons.tolist(), "y": y_moons.tolist()},
                                       separators=(",", ":")) + ";\n",
    encoding="utf-8")

reference = {
    "moons": {"X": X_moons.tolist(), "y": y_moons.tolist(),
              "kmeans_labels": km_moons.labels_.tolist(),
              "kmeans_ari": round(float(adjusted_rand_score(y_moons, km_moons.labels_)), 6),
              "kmeans_inertia": round(float(km_moons.inertia_), 6)},
    "scaler": {"mean": scaler.mean_.round(6).tolist(), "sd": scaler.scale_.round(6).tolist()},
    "score_only": {"good": lloyd(score_only, GOOD_START), "poor": lloyd(score_only, POOR_START),
                   "by_k": best_by_k(score_only, range(1, 7))},
    "two_d_raw": {"good": lloyd(two_d, GOOD_START), "poor": lloyd(two_d, POOR_START),
                  "by_k": best_by_k(two_d, range(1, 7))},
    "two_d_scaled": {"X": scaled.round(6).tolist(),
                     "good": lloyd(scaled, GOOD_START), "poor": lloyd(scaled, POOR_START),
                     "by_k": best_by_k(scaled, range(1, 7))},
}
# DBSCAN comparison data: three blobs that touch, where K-Means is the better choice.
X_blobs, y_blobs = make_blobs(n_samples=200, centers=3, cluster_std=1.0, random_state=4)
X_blobs = X_blobs.round(4)
(ROOT / "blobs.js").write_text(
    "// make_blobs(n_samples=200, centers=3, cluster_std=1.0, random_state=4), rounded to 4 decimals.\n"
    "// Generated by tests/make_reference.py.\n"
    "window.KM_BLOBS = " + json.dumps({"X": X_blobs.tolist(), "y": y_blobs.tolist()},
                                       separators=(",", ":")) + ";\n",
    encoding="utf-8")


def db_case(X, eps, min_samples, truth=None):
    model = DBSCAN(eps=eps, min_samples=min_samples).fit(X)
    case = {"eps": eps, "min_samples": min_samples, "labels": model.labels_.tolist(),
            "core": sorted(model.core_sample_indices_.tolist())}
    if truth is not None:
        case["ari"] = round(float(adjusted_rand_score(truth, model.labels_)), 6)
    return case


grid = [(adjusted_rand_score(y_blobs, DBSCAN(eps=float(e), min_samples=m).fit_predict(X_blobs)), round(float(e), 2), m)
        for e in np.arange(0.1, 3.01, 0.05) for m in range(2, 21)]
best_grid = max(grid)
km_blobs = KMeans(n_clusters=3, n_init=10, random_state=0).fit(X_blobs)
reference["dbscan"] = {
    "moons": [db_case(X_moons, e, m, y_moons) for e, m in [(0.3, 5), (0.1, 5), (0.2, 3), (0.5, 10)]],
    "blobs": {"X": X_blobs.tolist(), "y": y_blobs.tolist(),
              "cases": [db_case(X_blobs, e, m, y_blobs) for e, m in [(0.85, 11), (0.8, 5), (2.0, 4)]],
              "kmeans_ari": round(float(adjusted_rand_score(y_blobs, km_blobs.labels_)), 6),
              "grid_size": len(grid), "grid_best_ari": round(float(best_grid[0]), 6),
              "grid_best_eps": best_grid[1], "grid_best_min_samples": best_grid[2]},
    "score": [db_case(score_only, e, m) for e, m in [(5, 3), (3, 2), (15, 3)]],
}
print("blobs grid", len(grid), best_grid, "kmeans", reference["dbscan"]["blobs"]["kmeans_ari"])
print("moons dbscan ari", [c["ari"] for c in reference["dbscan"]["moons"]])

(ROOT / "tests" / "reference.json").write_text(json.dumps(reference, indent=1), encoding="utf-8")

for name in ("score_only", "two_d_raw", "two_d_scaled"):
    print(name, "good", reference[name]["good"]["inertia"], reference[name]["good"]["labels"],
          "poor", reference[name]["poor"]["inertia"], reference[name]["poor"]["labels"])
    print("   by k", {k: v["inertia"] for k, v in reference[name]["by_k"].items()})
print("moons ARI", reference["moons"]["kmeans_ari"], "inertia", reference["moons"]["kmeans_inertia"])
print("scaler", reference["scaler"])
